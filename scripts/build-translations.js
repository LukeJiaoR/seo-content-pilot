#!/usr/bin/env node
/**
 * Compile languages/*.po into:
 *  - languages/*.mo        (gettext binary, for PHP)
 *  - src/languages/<locale>.js  (JED ES module, for @wordpress/i18n)
 *
 * Usage: node scripts/build-translations.js
 */

const fs = require( 'fs' );
const path = require( 'path' );

const DOMAIN = 'seo-content-pilot';
const LANG_DIR = path.join( __dirname, '..', 'languages' );
const OUT_JS_DIR = path.join( __dirname, '..', 'src', 'languages' );

/** Parse a .po file into { headers, entries: [ { msgid, msgstr } ] }. */
function parsePo( content ) {
	const entries = [];
	const blocks = content.split( /\n\s*\n/ );
	for ( const block of blocks ) {
		const msgid = extractField( block, 'msgid' );
		const msgstr = extractField( block, 'msgstr' );
		if ( msgid !== null && msgstr !== null ) {
			entries.push( { msgid, msgstr } );
		}
	}
	return entries;
}

/** Extract a possibly multi-line msgid/msgstr field from a PO block. */
function extractField( block, field ) {
	const re = new RegExp( `^${ field }\\s+"((?:[^"\\\\]|\\\\.)*)"(\\s*\\n(?:\\s*"(?:[^"\\\\]|\\\\.)*"\\s*\\n?)*)?`, 'm' );
	const m = block.match( re );
	if ( ! m ) {
		return null;
	}
	let str = m[ 1 ];
	const cont = m[ 2 ] || '';
	for ( const cm of cont.matchAll( /"((?:[^"\\]|\\.)*)"/g ) ) {
		str += cm[ 1 ];
	}
	return unescape( str );
}

/** Unescape PO string escapes. */
function unescape( s ) {
	return s
		.replace( /\\n/g, '\n' )
		.replace( /\\t/g, '\t' )
		.replace( /\\"/g, '"' )
		.replace( /\\\\/g, '\\' );
}

/** Escape a JS single-quoted string. */
function jsEscape( s ) {
	return s
		.replace( /\\/g, '\\\\' )
		.replace( /'/g, "\\'" )
		.replace( /\n/g, '\\n' )
		.replace( /\r/g, '\\r' );
}

/** Build a .mo binary from entries. */
function buildMo( entries ) {
	// Sort by msgid bytes (gettext requires sorted order for bsearch).
	const sorted = [ ...entries ].sort( ( a, b ) =>
		Buffer.compare( Buffer.from( a.msgid, 'utf8' ), Buffer.from( b.msgid, 'utf8' ) )
	);

	const n = sorted.length;
	const msgidTableOffset = 28;
	const msgstrTableOffset = msgidTableOffset + n * 8;
	let stringsOffset = msgstrTableOffset + n * 8;

	const idOffsets = [];
	const strOffsets = [];
	let cursor = stringsOffset;
	for ( const e of sorted ) {
		const idBuf = Buffer.from( e.msgid, 'utf8' );
		idOffsets.push( { len: idBuf.length, off: cursor, buf: idBuf } );
		cursor += idBuf.length + 1;
	}
	for ( const e of sorted ) {
		const strBuf = Buffer.from( e.msgstr, 'utf8' );
		strOffsets.push( { len: strBuf.length, off: cursor, buf: strBuf } );
		cursor += strBuf.length + 1;
	}

	const total = cursor;
	const out = Buffer.alloc( total );
	let p = 0;
	out.writeUInt32LE( 0x950412de, p ); p += 4; // magic
	out.writeUInt32LE( 0, p ); p += 4; // revision
	out.writeUInt32LE( n, p ); p += 4; // count
	out.writeUInt32LE( msgidTableOffset, p ); p += 4;
	out.writeUInt32LE( msgstrTableOffset, p ); p += 4;
	out.writeUInt32LE( 0, p ); p += 4; // hash size
	out.writeUInt32LE( 0, p ); p += 4; // hash offset

	for ( const e of idOffsets ) {
		out.writeUInt32LE( e.len, p ); p += 4;
		out.writeUInt32LE( e.off, p ); p += 4;
	}
	for ( const e of strOffsets ) {
		out.writeUInt32LE( e.len, p ); p += 4;
		out.writeUInt32LE( e.off, p ); p += 4;
	}
	p = stringsOffset;
	for ( const e of idOffsets ) {
		e.buf.copy( out, p ); p += e.buf.length;
		out.writeUInt8( 0, p ); p += 1;
	}
	for ( const e of strOffsets ) {
		e.buf.copy( out, p ); p += e.buf.length;
		out.writeUInt8( 0, p ); p += 1;
	}
	return out;
}

/** Build the JED ES module source for @wordpress/i18n. */
function buildJedModule( entries, locale ) {
	const pairs = entries
		.filter( ( e ) => e.msgid !== '' )
		.map( ( e ) => `\t\t'${ jsEscape( e.msgid ) }': [ '${ jsEscape( e.msgstr ) }' ]` )
		.join( ',\n' );

	return `// Auto-generated by scripts/build-translations.js — do not edit.
const localeData = {
	'': {
		domain: '${ DOMAIN }',
		lang: '${ locale }',
		'plural-forms': 'nplurals=1; plural=0;',
	},
${ pairs },
};
export default {
	'translation-revision-date': '2026-09-30',
	generator: 'seo-content-pilot scripts/build-translations.js',
	domain: '${ DOMAIN }',
	locale_data: {
		'${ DOMAIN }': localeData,
	},
};
`;
}

// ---- main ----
if ( ! fs.existsSync( OUT_JS_DIR ) ) {
	fs.mkdirSync( OUT_JS_DIR, { recursive: true } );
}

const poFiles = fs.readdirSync( LANG_DIR ).filter( ( f ) => f.endsWith( '.po' ) );
for ( const file of poFiles ) {
	const m = file.match( new RegExp( `^${ DOMAIN }-(.+)\\.po$` ) );
	if ( ! m ) {
		console.warn( `Skipping ${ file } (does not match ${ DOMAIN }-<locale>.po)` );
		continue;
	}
	const locale = m[ 1 ];
	const entries = parsePo( fs.readFileSync( path.join( LANG_DIR, file ), 'utf8' ) );

	fs.writeFileSync( path.join( LANG_DIR, `${ DOMAIN }-${ locale }.mo` ), buildMo( entries ) );

	const jsName = locale.toLowerCase().replace( /_/g, '-' );
	fs.writeFileSync( path.join( OUT_JS_DIR, `${ jsName }.js` ), buildJedModule( entries, locale ) );

	console.log( `${ locale }: ${ entries.length } entries -> .mo + src/languages/${ jsName }.js` );
}
